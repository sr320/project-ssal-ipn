#!/bin/bash
# Gather per-library numbers for the dashboard and copy the small report
# files into the repository.
# Light enough for a klone login node; run it whenever jobs finish, then
# commit and push:
#   bash code/06-collect-metrics.sh && git add docs output && git commit -m "metrics" && git push
# Writes docs/metrics.js. Values not yet available are left out, and the
# dashboard shows them as pending. Alignment numbers are summed over the
# chunks of each library.
set -uo pipefail
source code/00-config.sh
field() { grep -h "$1" "${@:2}" 2>/dev/null | awk -F'\t' '{s+=$2} END{print s+0}'; }
pctof() { awk -v a="$1" -v b="$2" 'BEGIN{ if (b>0) printf "%.1f", 100*a/b }'; }

# MultiQC is built by code/02b-multiqc.sh (a job: the container does not
# start on login nodes). Here we only record whether each report is on gannet.
mq=""; pushed=false
for k in raw trimmed; do
  if wget --spider --quiet "$GANNET_WEB/output/qc/multiqc-$k/multiqc_report.html"; then mq="$mq $k: true,"; pushed=true; fi
done
[ -f "$QC/flowcell-lane.tsv" ] || cat "$QC"/fastqc-raw/*.flowcell.tsv > "$QC/flowcell-lane.tsv" 2>/dev/null

out=$REPO/docs/metrics.js
{
  echo "// Generated by code/06-collect-metrics.sh on $(date '+%Y-%m-%d %H:%M %Z'). Do not edit."
  echo "window.GANNET = \"$GANNET_WEB/output\";"
  echo "window.MULTIQC = {$mq onGannet: $pushed };"
  echo "window.METRICS = {"
  for s in $(all_samples); do
    f=""
    [ -f "$QC/fastqc-raw/$s.done" ] && f="$f rawqc: true,"
    v=$(grep -m1 "Pairs written" "$TRIM/$s.pass2.log" 2>/dev/null | grep -oE '[0-9.]+%' | tr -d '%'); [ -n "$v" ] && f="$f trimKept: $v,"
    if [ -f "$DEDUP/$s.done" ]; then
      reps=("$ALN/${s}"_1.chunk*_PE_report.txt)
      v=$(pctof "$(field 'unique best hit' "${reps[@]}")" "$(field 'Sequence pairs analysed in total' "${reps[@]}")"); [ -n "$v" ] && f="$f mapping: $v,"
      for ctx in CpG CHH; do
        m=$(field "Total methylated C's in $ctx context" "${reps[@]}"); u=$(field "Total unmethylated C's in $ctx context" "${reps[@]}")
        v=$(pctof "$m" $((m + u))); [ -n "$v" ] && f="$f $(echo $ctx | tr 'A-Z' 'a-z'): $v,"
      done
      v=$(grep -m1 "duplicated alignments removed" "$DEDUP/$s.deduplication_report.txt" 2>/dev/null | grep -oE '[0-9.]+%' | tr -d '%'); [ -n "$v" ] && f="$f dup: $v,"
    fi
    [ -f "$METH/$s.done" ] && f="$f extracted: true,"
    [ -f "$METH/$s.coverage.tsv" ] && f="$f $(awk -F'\t' 'NR==2{printf "cpgDepth: %s, ge1: %s, ge5: %s, ge10: %s,", $3, $4, $6, $7}' "$METH/$s.coverage.tsv")"
    [ -f "$METH/$s.archived" ] && f="$f archived: true,"
    echo "  \"$s\": {$f },"
  done
  echo "};"
} > "$out"
echo "wrote $out"

mkdir -p "$REPO"/output/{02-fastqc-raw,04-trim,04-bismark,04-dedup,05-methylation}
cp "$QC/flowcell-lane.tsv" "$REPO/output/02-fastqc-raw/" 2>/dev/null
cp "$TRIM"/*.log "$REPO/output/04-trim/" 2>/dev/null
cp "$ALN"/*_PE_report.txt "$REPO/output/04-bismark/" 2>/dev/null
cp "$DEDUP"/*deduplication_report.txt "$REPO/output/04-dedup/" 2>/dev/null
cp "$METH"/mbias/*M-bias.txt "$METH"/*splitting_report.txt "$METH"/*.coverage*.tsv "$REPO/output/05-methylation/" 2>/dev/null
true
